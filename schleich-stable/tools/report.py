#!/usr/bin/env python3
"""Write docs/PRINT_PLAN.md and docs/BOM.md from build/plates.json,
build/slice.json and the instance registry (run tools/plates.py first)."""
import json, os, sys
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
from build import read_instances, unique_parts  # noqa: E402

plates = json.load(open(os.path.join(ROOT, "build", "plates.json")))
slices = json.load(open(os.path.join(ROOT, "build", "slice.json")))["parts"]
val = json.load(open(os.path.join(ROOT, "build", "validation.json")))
parts = unique_parts(read_instances())
main = {k: v for k, v in plates.items() if k.startswith("P")}
# pin lengths from the virtual pins of the validation (mm)
pin_len = {}
for pn in val.get("pins", []):
    kind = pn["pin"].split("_")[1]
    pin_len[kind] = max(pin_len.get(kind, 0), pn["length_mm"])


def ids(word):
    """plate ids (P..) whose name contains word, as a compact range string"""
    k = sorted(p.split("_")[0] for p in main if word in p)
    return (k[0] + ("-" + k[-1] if len(k) > 1 else "")) if k else "-"

COLOUR = {"floor": "grey", "post": "black", "wall": "white", "door": "black", "roof": "dark grey"}
PLATE_COLOUR = {"grey": "grey", "black": "black", "white": "white", "roof": "dark grey", "any": "any"}


def hm(s):
    return f"{int(s // 3600)} h {int(s % 3600 // 60):02d} min"


# ------------------------------------------------------------------ plan
L = ["# Print plan (Bambu Lab A1)", "",
     "Generated by `tools/report.py`. Times and weights are **estimates** from PrusaSlicer 2.7.2",
     "with A1-equivalent speeds and accelerations (`tools/a1_pla_estimate.ini`). Nothing was",
     "printed. Bambu Studio's own estimate will differ, possibly by +-20 %.", "",
     "## Recommended settings", "",
     "| Setting | Value | Why |", "|---|---|---|",
     "| Material | PLA or PLA+ (PETG optional for doors) | stiff, easy, low warp; PETG flexes more forgivingly in the latch tongues |",
     "| Nozzle | 0.4 mm | details (board grooves 1.1 mm, latch 1.8 mm tongue) are sized for it |",
     "| Layer height | 0.20 mm (Bambu \"0.20mm Standard @BBL A1\") | 0.16 mm for the doors is optional |",
     "| Wall loops | 3 | stronger panels, grooves and sockets |",
     "| Top / bottom shells | 5 / 4 | flat textured surfaces close well |",
     "| Sparse infill | 15 % grid (gyroid also fine) | floor tiles and plinth are modelled solid |",
     "| Supports | **off** for every part | everything is designed support-free |",
     "| Brim | 5 mm for the posts (upright) and the central roof units | tall, narrow footprints |",
     "| Plate | Textured PEI, 65 C (Bambu PLA default) | textured underside looks good on panels |",
     "| Seam | Aligned or back | |",
     "| Part cooling | Bambu PLA default | 45 deg overhangs on the central roof need good cooling |", "",
     "### Black trim on white panels (optional)", "",
     "White panels carry raised trims (window frames, rails, the door arch, bars) from **Z = 2.8 mm**.",
     "In Bambu Studio's preview, right-click the layer slider at 2.8 mm, the last white layer, and choose",
     "**Add color change** (AMS / AMS lite) or **Add pause** (no AMS: swap to black when it",
     "pauses). Plates marked \"trim\" below benefit from this. The trim can also be left white or",
     "painted.", "",
     "## Plates", "",
     "Print the test plates **T1/T2 first** (see `TESTING.md`) and adjust `config.scad` if needed.", "",
     "![All print plates (rendered from the plate files)](images/plates.png)", "",
     "| Plate (3MF) | Parts | Colour | Est. time | Est. filament |", "|---|---|---|---|---|"]
tot_t = defaultdict(float); tot_g = defaultdict(float)
for pid, p in plates.items():
    names = ", ".join(p["parts"])
    col = PLATE_COLOUR.get(p["colour"], p["colour"]) + (" + black trim (optional)" if p.get("note") == "trim" else "")
    extra = f" ({p['note']})" if p.get("note") and p["note"] != "trim" else ""
    L.append(f"| `{pid}.3mf` | {names}{extra} | {col} | {hm(p.get('time_s', 0))} | {p.get('filament_g', 0):.0f} g |")
    if pid.startswith("P"):
        tot_t[p["colour"]] += p.get("time_s", 0); tot_g[p["colour"]] += p.get("filament_g", 0)
L += ["", f"## Totals for the stable ({len(main)} plates, test plates excluded)", "",
      "| Colour | Time | Filament |", "|---|---|---|"]
for c in tot_t:
    L.append(f"| {PLATE_COLOUR.get(c, c)} | {hm(tot_t[c])} | {tot_g[c] / 1000:.2f} kg |")
L.append(f"| **all** | **{hm(sum(tot_t.values()))}** | **{sum(tot_g.values()) / 1000:.2f} kg** |")
need = {c: g * 1.1 / 1000 for c, g in tot_g.items()}
L += ["", "Filament to have on hand (estimate + 10 % for purge, brims and failed prints): " +
      ", ".join(f"{PLATE_COLOUR.get(c, c)} {v:.2f} kg" for c, v in need.items()) + ".",
      f"The roof can also use the black spool (black then {need.get('black', 0) + need.get('roof', 0):.2f} kg).", "",
      "## Recommended order", "",
      "1. **T1, T2** test coupons, then evaluate them (TESTING.md).",
      f"2. **{ids('posts')}** posts. The tall posts take longest; let them run overnight.",
      f"3. **{ids('floor')}** floor tiles. Assemble the base as soon as two tiles are done.",
      f"4. **{ids('walls')}** walls, partitions, stall fronts, pediments (white, optional trim change).",
      f"5. **{ids('doors')}** doors and windows (black). PETG optional.",
      f"6. **{ids('roof')}** roof.", "",
      "## Orientation notes", "",
      "* All 3MF plates are already oriented and arranged; the individual STLs in `stl/` are in print orientation too.",
      "* Posts stand upright (grooves and hinge bores print round and strong).",
      "* The central roof units print standing on their eave edges, as installed. Use a 5 mm brim and keep the plate clean.",
      "* Everything else prints flat. The exterior or show face is up.",
      "* If the first layer of the large panels lifts at the corners: clean the plate (soap and water), raise the bed temperature by 5 C, add a 3 mm brim.", ""]
open(os.path.join(ROOT, "docs", "PRINT_PLAN.md"), "w").write("\n".join(L) + "\n")

# ------------------------------------------------------------------- BOM
used_on = defaultdict(list)
for pid, p in plates.items():
    for n in p["parts"]:
        used_on[n].append(pid.split("_")[0])
B = ["# Bill of materials", "", "Generated by `tools/report.py`.", "",
     f"## Printed parts ({len(parts)} unique STL files, {sum(q for _, _, q in parts)} pieces)", "",
     "| STL (`stl/`) | Qty | Colour | Plates | Est. g each |", "|---|---|---|---|---|"]
for p, c, q in parts:
    g = slices.get(p, {}).get("filament_g", 0)
    B.append(f"| `{p}.stl` | {q} | {COLOUR[c]} | {', '.join(sorted(set(used_on[p])))} | {g:.0f} |")
B += ["", "Mirror pairs (`_A` / `_B`, `_L` / `_R`) are different files. Each is printed twice.",
      "Parts listed with qty 4 are identical, because they are rotated copies of each other",
      "(all four stall fronts and all four stall doors are the same part).", "",
      "## Hardware", "",
      "| Item | Qty | Notes |", "|---|---|---|",
      f"| Hinge pin, main door: 1.75 mm filament, **{pin_len.get('main', 0):.0f} mm** | 4 | inserted from below, captured by the floor |",
      f"| Hinge pin, stall door: 1.75 mm filament, **{pin_len.get('stall', 0):.0f} mm** | 4 | inserted from below, captured by the floor |",
      f"| Hinge pin, casement: 1.75 mm filament, **{pin_len.get('case', 0):.0f} mm** | 4 | dropped in from above |",
      f"| Total filament for pins | about {4 * sum(pin_len.values()) / 1000 + 0.05:.2f} m | PLA or PETG; straighten a piece from the spool and cut with flush cutters |",
      "| *Option:* 2.0 mm steel rod instead of filament | as above | set `pin_d = 2.0`, `bore_fixed = 2.1`, `bore_free = 2.55`, re-export doors and posts |", "",
      "No screws, magnets or glue are needed.", "",
      "## Tools", "",
      "* Flush cutters (pins, brims)",
      "* Optional: a 1.8 mm drill bit, by hand, to clean a tight hinge bore; fine sandpaper",
      "* Optional: black acrylic paint pen for trims if you print single-colour", ""]
open(os.path.join(ROOT, "docs", "BOM.md"), "w").write("\n".join(B) + "\n")
print("wrote docs/PRINT_PLAN.md, docs/BOM.md")
